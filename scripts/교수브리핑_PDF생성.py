    fig, ax = plt.subplots(figsize=(7.2, 2.3))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 3.2)
    ax.axis('off')
    w, gap = 1.62, 0.44
    for i, (t, sub, pay) in enumerate(steps):
        x0 = 0.05 + i * (w + gap)
        ax.add_patch(FancyBboxPatch((x0, 1.25), w, 1.35, boxstyle='round,pad=0,rounding_size=0.08',
                                    fc='#FBE3E0' if pay else 'white', ec=RED if pay else '#555555', lw=1.2))
        ax.text(x0 + w / 2, 2.12, t, ha='center', va='center', fontsize=9.5, fontweight='bold')
        ax.text(x0 + w / 2, 1.5, sub, ha='center', va='center', fontsize=8, color=RED if pay else '#555555')
        if i < len(steps) - 1:
            ax.annotate('', xy=(x0 + w + gap - 0.04, 1.92), xytext=(x0 + w + 0.04, 1.92),
                        arrowprops=dict(arrowstyle='->', color='#333333', lw=1))
    ax.text(0.05, 0.75, '참여자 총본인부담액 = 지출 ① + 지출 ②', fontsize=9)
    ax.text(0.05, 0.25, '안동 내 추가 소비 = 시행 시 지출 - 사업이 없었을 때 지출 - 기존 상권에서 줄어든 소비', fontsize=9)
