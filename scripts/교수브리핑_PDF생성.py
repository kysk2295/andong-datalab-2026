def save(fig, name):
    fig.savefig(D / name, format='svg', bbox_inches='tight', facecolor='white')
    fig.savefig(D / name.replace('.svg', '.png'), format='png', dpi=200, bbox_inches='tight', facecolor='white')  # 워드용
    plt.close(fig)
    return name


def style(ax):
    ax.grid(axis='y', color='#E5E5E5', lw=0.7)
    ax.set_axisbelow(True)


def chart_cities():
    order = ['안동', '경주', '군산', '포항', '전주']
    v = [C5[c]['방문'] for c in order]
    s = [C5[c]['방문당소비'] for c in order]
    fig, ax = plt.subplots(figsize=(7.2, 2.9))
    x = list(range(len(order)))
    w = 0.36
    b1 = ax.bar([i - w / 2 for i in x], v, w, color=[RED_L if c == '안동' else GRAY_L for c in order], label='방문 증감률')
    b2 = ax.bar([i + w / 2 for i in x], s, w, color=[RED if c == '안동' else GRAY for c in order], label='방문당 관광소비 증감률')
    for bars in (b1, b2):
        for r in bars:
            h = r.get_height()
            ax.text(r.get_x() + r.get_width() / 2, h + (0.3 if h >= 0 else -0.3), f'{h:+.1f}%',
                    ha='center', va='bottom' if h >= 0 else 'top', fontsize=8.5)
    ax.axhline(0, color='#555555', lw=0.8)
    ax.set_xticks(x, order)
    for t in ax.get_xticklabels():
        if t.get_text() == '안동':
            t.set_color(RED)
            t.set_fontweight('bold')
    ax.set_ylabel('증감률(%)')
    ax.set_ylim(-5, 12)
    style(ax)
    ax.legend(frameon=False, loc='upper left', fontsize=8.5)
    ax.set_title('5개 도시 방문 및 방문당 관광소비 증감률 (2024 → 2026년 1~8월)')
    return save(fig, 'fig1_5개도시.svg')


