def table(head, rows, cls='', hl_rows=()):
    th = ''.join(f'<th>{h}</th>' for h in head)
    tr = ''.join(f'<tr{" class=hl" if i in hl_rows else ""}>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>'
                 for i, r in enumerate(rows))
    return f'<table class="{cls}"><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table>'


def cap(t):
    return f'<p class="cap">&lt; {t} &gt;</p>'


