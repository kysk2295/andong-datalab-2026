def chart_synth():
    import math
    t = list(range(-24, 13))
    comp = [100 + 0.25 * k + 2.2 * math.sin(k / 2.2) for k in t]
    ad = [c + 0.6 * math.sin(k * 1.3) if k < 0 else c + 0.55 * k for k, c in zip(t, comp)]
    fig, ax = plt.subplots(figsize=(7.2, 2.9))
    ax.plot(t, comp, color=GRAY, lw=1.6, ls='--', label='비교 조합 (주민증은 운영, 릴레이는 없는 지역들)')
    ax.plot(t, ad, color=RED, lw=2, label='안동')
    post = [k for k in t if k >= 0]
    ax.fill_between(post, [comp[t.index(k)] for k in post], [ad[t.index(k)] for k in post], color=RED_L, alpha=0.35, lw=0)
    ax.axvline(0, color='#333333', lw=0.9)
    ax.text(0.4, max(ad) + 0.3, '사업 시작', fontsize=8.5, va='top')
    ax.text(8, (comp[-4] + ad[-4]) / 2, '효과', fontsize=9, color=RED, fontweight='bold', ha='center', va='center')
    ax.text(-23.5, max(ad) + 0.3, '예시: 방법을 보여주는 모양이며 실제 값이 아니다', fontsize=8.5, color='#666666', va='top')
    ax.set_xticks([-12, 6], ['시행 전: 두 선이 겹쳐야 비교를 믿을 수 있다', '시행 후: 벌어진 차이를 효과로 본다'])
    ax.tick_params(axis='x', length=0)
    ax.set_yticks([])
    ax.set_ylabel('방문당 체험·문화 소비')
    ax.legend(frameon=False, loc='lower right', fontsize=8.5)
    ax.set_title('사후 효과 검증 방식 (비교 조합과 대조)')
