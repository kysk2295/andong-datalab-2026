# -*- coding: utf-8 -*-
"""릴레이 1~3단계 최종 결과물(①식음→체험 연결표 ②운행 시각표 ③교통 공백 ④야간 팝업 구성안 ⑤효과표)의 값.

팀 아티팩트 「만들 것과 조사할 것」 1장 카드의 '나오는 모양'을 실제 값으로 채운다.
입력: 보고서/교수브리핑_20260922/수치.json, 보고서/성과도출_20260922/성과도출_수치.json(scripts/성과도출_데이터.py), 조사/03·10·12·16
출력: 보고서/성과도출_20260922/최종성과물_수치.json
"""
import json, pandas as pd, numpy as np

Q = json.load(open('보고서/교수브리핑_20260922/수치.json'))
S = json.load(open('보고서/성과도출_20260922/성과도출_수치.json'))
R = {}
WKND_DAYS = int((pd.date_range('2026-01-01', '2026-08-31').dayofweek >= 5).sum())   # 70일
R['주말일수_2026_1_8'] = WKND_DAYS

# ── ① 식음 → 체험 연결표 ────────────────────────────────────────────
ex = pd.read_excel('조사/03_체험프로그램_목록가격.xlsx', sheet_name='체험프로그램')
def 권역(a):
    a = str(a)
    if '풍천' in a or '하회' in a: return '하회'
    if '도산' in a: return '도산'
    if '풍산' in a: return '풍산'
    if '민속촌길' in a or '석주로' in a: return '월영교'
    if '강남로' in a: return '강남동(소주박물관)'
    return '기타'
ex['권역'] = ex['주소'].map(권역)
R['체험'] = ex[['체험명', '권역', '가격', '운영 시작', '운영 종료', '저녁연결(18시 이후)']].fillna('').to_dict('records')

s60 = pd.read_csv('조사/12_원도심_식당영업시간_표본60.csv')
s60 = s60[s60['점포별_영업종료'].notna()]
R['원도심식당_영업종료'] = s60[['상호', '구역', '점포별_영업시작', '점포별_영업종료']].to_dict('records')

# ── ② 운행 시각표: 주말 외지인 방문 시간대 vs 안동역 주말 승차 (같은 6구간) ──────
f = 'data/bdt/이동통신/방문자수_성별연령요일시간대_교차표_BDT_01_01_006_2026.csv'
parts = []
for ch in pd.read_csv(f, chunksize=2_000_000,
                      usecols=['R:기초단체', 'R:기준연월', 'C:방문자유형별', 'C:요일', 'C:시간대', 'V:방문자 수']):
    ch = ch[(ch['R:기초단체'] == '안동시') & (ch['C:방문자유형별'] == '외지인(b)') & ch['C:시간대'].notna()
            & ((ch['R:기준연월'] % 100) <= 8) & ch['C:요일'].isin(['토요일', '일요일'])]
    parts.append(ch.groupby('C:시간대')['V:방문자 수'].sum())
vis = pd.concat(parts).groupby(level=0).sum()
B = ['06~11시', '11~14시', '14~18시', '18~21시', '21~24시']
vis = vis[B]
st = Q['안동역_주말승차']
rng = {'06~11시': range(6, 11), '11~14시': range(11, 14), '14~18시': range(14, 18),
       '18~21시': range(18, 21), '21~24시': range(21, 24)}
ride = pd.Series({b: sum(st.get(f'{h:02d}-{h + 1:02d}', 0) for h in hs) for b, hs in rng.items()})
R['운행_두분포'] = [{'시간대': b, '외지인방문_비중': float(vis[b] / vis.sum() * 100),
                   '안동역승차_비중': float(ride[b] / ride.sum() * 100),
                   '외지인방문_주말하루': float(vis[b] / WKND_DAYS), '안동역승차_주말하루': float(ride[b] / WKND_DAYS)}
                  for b in B]

# ── 수요(주말 저녁 하루) → 운행·부스의 규모감 ─────────────────────────
opp3 = S['3단계']['방문기회_주말저녁_2026_1_8']
per_eve = opp3 / WKND_DAYS                                  # 강남동 18~21시 외지인 방문, 주말 하루 평균
RATES = {'보수': S['1단계']['주민증_이용률_기준선_pct'], '기준': S['3단계']['하회마을_이용률_pct'], '낙관': 5.0}
R['참여율'] = RATES
R['참여율_근거'] = {'보수': '안동 주민증 평균 이용률(월 887.5건 ÷ 월 외지인 방문, 실측)',
                  '기준': '혜택이 있는 하회마을의 주민증 이용률(이용 표시값 ÷ 입장객, 실측·상한 쪽)',
                  '낙관': '가정 — 혜택을 반값여행 수준으로 키운 경우를 상정, 근거 자료 없음'}
R['주말저녁_월영교권역_하루'] = per_eve
R['주말저녁_하루_참여자'] = {k: per_eve * r / 100 for k, r in RATES.items()}
R['택시4인_하루_필요운행'] = {k: np.ceil(v / 4) for k, v in R['주말저녁_하루_참여자'].items()}

# ── ③ 교통 공백 ───────────────────────────────────────────────────
R['버스'] = Q['버스']

# ── ④ 야간 팝업: 월영교 1km 21시 이후 공급 vs 원도심 업종 구성 ─────────────
w = pd.DataFrame(Q['월영교조사'])
w = w[w['상태'] == '영업']
w['업종'] = w['상권업종중분류명'].str.strip().replace({'비알코올': '카페(비알코올)'})
w['21시후'] = w['영업종료'].fillna('00:00') > '21:00'
sup = w.groupby('업종').agg(영업=('상호명', 'size'), 이후21시=('21시후', 'sum'))
R['월영교_21시이후_공급'] = {k: {'영업': int(r['영업']), '21시이후': int(r['이후21시'])} for k, r in sup.iterrows()}
R['원도심_업종'] = Q['반경1km업종']
cases = pd.read_excel('조사/10_야시장_운영사례.xlsx', sheet_name='사례')
R['야시장_부스범위'] = [int(cases['부스 수'].iloc[2:9].min()), int(cases['부스 수'].iloc[2:9].max())]

# ── ⑤ 효과표 (보수·기준·낙관) ─────────────────────────────────────
V26 = Q['방문']['2026_1-8']
EXP26 = Q['체험문화']['안동_2026']
emd = pd.read_csv('data/api_region/안동_읍면동별_외지인_월별_BDT_01_01_005_1.csv')
jg = float(emd[(emd.AREA_NM == '중구동') & (emd.BASE_YM // 100 == 2026) & (emd.BASE_YM % 100 <= 8)].TOU_NUM.sum())
opp1 = jg * S['2단계']['주말방문비중'] / 100               # 원도심(중구동) 주말 외지인 방문
PRICE1 = {'보수': 10000, '기준': 15000, '낙관': 20000}      # 조사/03 체험 가격대(공예 5천~3.9만, 구름에 1.2~2.2만)
unit = S['3단계']['축제객단가']
PRICE2 = {'보수': unit['P10'], '기준': unit['중앙'], '낙관': unit['P90']}
CF = S['3단계']['반사실몫_가정']
GN = S['3단계']['강남동_외지인관광소비_2026_1_8_원']
eff = {}
for k, r in RATES.items():
    n1, n2 = opp1 * r / 100, opp3 * r / 100
    g1, g2 = n1 * PRICE1[k], n2 * PRICE2[k]
    eff[k] = {'참여율_pct': r, '방문기회_1단계': opp1, '방문기회_3단계': opp3,
              '체험이용': n1, '팝업이용': n2, '체험가격': PRICE1[k], '팝업객단가': PRICE2[k],
              '총본인부담_체험': g1, '총본인부담_팝업': g2, '총본인부담_합': g1 + g2,
              '추가소비_체험': g1 * (1 - CF), '추가소비_팝업': g2 * (1 - CF), '추가소비_합': (g1 + g2) * (1 - CF),
              '방문당체험문화_증가_pct': g1 * (1 - CF) / V26 / EXP26 * 100,
              '강남동관광소비_증가_pct': g2 * (1 - CF) / GN * 100}
R['효과표'] = eff
R['중구동_외지인방문_2026_1_8'] = jg

json.dump(R, open('보고서/성과도출_20260922/최종성과물_수치.json', 'w'), ensure_ascii=False, indent=1, default=float)

print('주말일수', WKND_DAYS, ' 월영교권역 주말저녁 하루', round(per_eve))
for x in R['운행_두분포']: print(f"  {x['시간대']} 방문 {x['외지인방문_비중']:.1f}% 승차 {x['안동역승차_비중']:.1f}%  하루 방문 {x['외지인방문_주말하루']:,.0f} 승차 {x['안동역승차_주말하루']:,.0f}")
print('하루 참여자', {k: round(v, 1) for k, v in R['주말저녁_하루_참여자'].items()}, '택시', R['택시4인_하루_필요운행'])
print('월영교 21시 이후', R['월영교_21시이후_공급'])
print('야시장 부스', R['야시장_부스범위'])
for k, e in eff.items():
    print(f"  {k} {e['참여율_pct']:.3f}%  체험 {e['체험이용']:,.0f}건 팝업 {e['팝업이용']:,.0f}명  총 {e['총본인부담_합']/1e8:.2f}억 추가 {e['추가소비_합']/1e8:.2f}억  체험문화 +{e['방문당체험문화_증가_pct']:.2f}% 강남동 +{e['강남동관광소비_증가_pct']:.2f}%")
