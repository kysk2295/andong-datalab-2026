def sheet(title, header, rows, widths, note=None):
    ws = wb.create_sheet(title)
    r0 = 1
    if note:
        ws.cell(1, 1, note).font = FB
        ws.cell(1, 1).alignment = WRAP
        ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(header))
        ws.row_dimensions[1].height = 48
        r0 = 3
    for j, h in enumerate(header, 1):
        c = ws.cell(r0, j, h); c.font = FB; c.fill = HEAD; c.border = BOX; c.alignment = WRAP
    for i, row in enumerate(rows, r0 + 1):
        for j, v in enumerate(row, 1):
            c = ws.cell(i, j, v); c.font = F; c.border = BOX; c.alignment = WRAP
            if isinstance(v, float):
                c.number_format = '#,##0.00'
            elif isinstance(v, int):
                c.number_format = '#,##0'
    for j, w in enumerate(widths, 1):
        ws.column_dimensions[chr(64 + j)].width = w
    ws.freeze_panes = ws.cell(r0 + 1, 1)
    return ws


